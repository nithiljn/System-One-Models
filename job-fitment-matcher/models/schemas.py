"""
Data Schemas and Validation Contracts.
Defines Pydantic request and response models for fitment matching and deep resume auditing.
"""

from typing import List
from pydantic import BaseModel, Field, field_validator


class FitmentRequest(BaseModel):
    """
    Incoming request schema for candidate fitment evaluation.
    Enforces minimum and maximum character limits to prevent empty submissions and token abuse.
    """

    job_description: str = Field(
        ...,
        min_length=30,
        max_length=15000,
        description="Full text of the target job description including requirements and responsibilities.",
    )

    resume_content: str = Field(
        ...,
        min_length=30,
        max_length=20000,
        description="Extracted text of the candidate's resume, skills, and work history.",
    )

    @field_validator("job_description", "resume_content")
    @classmethod
    def sanitize_and_strip_whitespace(cls, text_value: str) -> str:
        """
        Removes leading and trailing whitespace from input text.
        Ensures the input contains meaningful text rather than just blank spaces.
        """
        cleaned_text = text_value.strip()
        if len(cleaned_text) < 30:
            raise ValueError("Input text must contain at least 30 non-whitespace characters.")
        return cleaned_text


class FitmentResponse(BaseModel):
    """
    Outgoing response schema containing the System-1 calibrated decisions.
    Returned directly to the frontend interface.
    """

    is_eligible: bool = Field(
        ...,
        description="Binary decision on whether the candidate satisfies the fundamental qualifications.",
    )

    eligibility_confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Calibrated probability percentage for the eligibility decision.",
    )

    fit_tier: str = Field(
        ...,
        description="Categorical fitment tier: Strong Match, Moderate Match, or Skill Gap.",
    )

    tier_confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence percentage for the selected fitment category.",
    )

    match_score: float = Field(
        ...,
        ge=0.0,
        le=10.0,
        description="Continuous weighted rubric match score on a scale from 0.0 to 10.0.",
    )

    has_dealbreakers: bool = Field(
        ...,
        description="True if strict non-negotiable requirements are completely missing.",
    )

    dealbreaker_confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence score for the dealbreaker evaluation.",
    )

    latency_ms: float = Field(
        ...,
        description="Round-trip latency in milliseconds for the Gemini Decision evaluation.",
    )

    output_tokens_billed: int = Field(
        default=0,
        description="Count of output tokens billed by the Decisions API (always 0).",
    )


class AuditRequest(BaseModel):
    """
    Incoming request schema for the optional on-demand System-2 deep resume audit.
    """

    job_description: str = Field(
        ...,
        min_length=30,
        max_length=15000,
        description="The original job description requirements.",
    )

    resume_content: str = Field(
        ...,
        min_length=30,
        max_length=20000,
        description="The candidate resume content to audit.",
    )


class AuditResponse(BaseModel):
    """
    Outgoing response schema for the on-demand resume improvement audit.
    Provides actionable constructive feedback generated by the audit model.
    """

    missing_skills: List[str] = Field(
        default_factory=list,
        description="List of essential skills mentioned in the job description but missing from the resume.",
    )

    resume_red_flags: List[str] = Field(
        default_factory=list,
        description="Identified issues such as spelling errors, unrelated fluff, or unnecessary over-engineering.",
    )

    actionable_recommendations: List[str] = Field(
        default_factory=list,
        description="Concrete steps and projects the candidate can complete to qualify for the role.",
    )

    latency_ms: float = Field(
        ...,
        description="Time taken in milliseconds to generate the deep audit critique.",
    )
